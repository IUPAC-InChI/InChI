@pytest.mark.skipif(sys.platform == "win32", reason="/dev/stdin is POSIX-only")
def test_reads_molfile_from_dev_stdin(request):
    exe_path: str = request.config.getoption("--exe-path")
    if not Path(exe_path).exists():
        raise FileNotFoundError(f"InChI executable not found at {exe_path}.")

    result = subprocess.run(
        [exe_path, "/dev/stdin", "-STDIO", "-Key", "-AuxNone"],
        input=MOLFILE,
        capture_output=True,
        text=True,
    )

    assert result.returncode == 0, result.stderr
    assert "Cannot interpret" not in result.stderr
    assert EXPECTED_INCHIKEY in result.stdout
